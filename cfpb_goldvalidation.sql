CREATE OR REPLACE TABLE CFPB_DB.GOLD.GOLD_COMPLAINTS_BY_MONTH_PRODUCT_CLEAN AS
SELECT
    TRY_TO_DATE(C1, 'DD-MM-YYYY') AS COMPLAINT_MONTH,
    C2                            AS PRODUCT_5,
    TRY_CAST(C3 AS NUMBER)        AS DISTINCT_COMPLAINTS
FROM CFPB_DB.GOLD.GOLD_COMPLAINTS_BY_MONTH_PRODUCT
WHERE TRY_TO_DATE(C1, 'DD-MM-YYYY') IS NOT NULL;

